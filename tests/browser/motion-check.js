(async()=>{
  const run=new URLSearchParams(location.search).get('run')||'motion';
  const result={suite:'bar',run,checks:[],failures:[]};
  const wait=async test=>{const end=Date.now()+5000;while(!test()){if(Date.now()>end)throw Error('等待条件超时');await new Promise(r=>setTimeout(r,20));}};
  const check=(name,condition)=>{if(!condition)throw Error(name);result.checks.push(name);};
  try{
    await wait(()=>document.getElementById('floating-bookmarks-extension')?.shadowRoot.querySelector('.bookmark'));
    const host=document.getElementById('floating-bookmarks-extension'),s=host.shadowRoot;
    const pointerIsolation=document.createElement('style');pointerIsolation.textContent='*{pointer-events:none!important}';s.append(pointerIsolation);
    await chrome.runtime.sendMessage({type:'SET_SETTINGS',patch:{enabled:true,pinned:true,rootId:'auto',excludedHosts:[]}});
    const design=fixture.tree[0].children[0].children.find(n=>n.id==='18');
    const previousDesignButton=s.querySelector('.bookmark[title="设计"]');
    const links=n=>Array.from({length:n},(_,i)=>({id:`motion-${n}-${i}`,title:`收藏 ${i+1}`,url:`https://example.com/${n}/${i}`}));
    design.children=[...links(8),{id:'motion-child-a',title:'子菜单一',children:links(1)},{id:'motion-child-b',title:'子菜单二',children:links(4)}];
    fixture.messages.fire({type:'BOOKMARKS_CHANGED'});
    await wait(()=>s.querySelector('.bookmark[title="设计"]')!==previousDesignButton);
    const click=title=>s.querySelector(`.bookmark[title="${title}"]`).click();
    const hover=title=>s.querySelector(`.bookmark[title="${title}"]`).dispatchEvent(new PointerEvent('pointerenter'));
    const settle=async()=>{
      const animations=[...s.querySelectorAll('.panel')].flatMap(p=>p.getAnimations({subtree:true}));
      animations.push(...s.querySelector('.bookmark-selection').getAnimations());
      await Promise.all(animations.map(a=>a.finished.catch(()=>{})));
    };
    const boxMotion=panel=>panel.getAnimations().find(a=>a.effect.getKeyframes().some(frame=>'left' in frame));
    click('网盘');await settle();
    const before=s.querySelector('.panel').getBoundingClientRect();
    hover('设计');
    let panel=s.querySelector('.panel'),motion=boxMotion(panel);
    check('同级切换启动位置和尺寸动画',!!motion&&panel.classList.contains('is-switching'));
    const frames=motion.effect.getKeyframes(),target=frames.at(-1);
    check('从旧菜单当前位置开始',Math.abs(parseFloat(frames[0].left)-before.left)<1&&Math.abs(parseFloat(frames[0].height)-before.height)<1);
    motion.pause();motion.currentTime=95;
    let middle=panel.getBoundingClientRect();
    check('中途位置在起点和终点之间',middle.left>Math.min(before.left,parseFloat(target.left))&&middle.left<Math.max(before.left,parseFloat(target.left)));
    check('中途高度平滑改变',middle.height>before.height&&middle.height<parseFloat(target.height));
    check('菜单内容单独过渡而不缩放文字',panel.querySelector('.panel-body').getAnimations().some(a=>a.effect.getKeyframes().some(f=>String(f.transform).includes('translateX')))&&!frames.some(f=>String(f.transform).includes('scale')));
    motion.play();await settle();
    check('完成后恢复滚动和自然高度',!panel.classList.contains('is-switching')&&Math.abs(panel.getBoundingClientRect().height-parseFloat(target.height))<1);
    hover('网盘');
    const interrupted=s.querySelector('.panel'),oldMotion=boxMotion(interrupted);
    oldMotion.pause();oldMotion.currentTime=60;
    const interruptedBox=interrupted.getBoundingClientRect();
    hover('程序员');
    panel=s.querySelector('.panel');motion=boxMotion(panel);
    check('打断后从当前帧接续',Math.abs(parseFloat(motion.effect.getKeyframes()[0].left)-interruptedBox.left)<1);
    check('旧动画取消且没有旧菜单残留',oldMotion.playState==='idle'&&!interrupted.isConnected&&s.querySelectorAll('.panel').length===1);
    for(const title of ['设计','常用网站','网盘','程序员'])hover(title);
    await settle();
    panel=s.querySelector('.panel');
    check('快速切换以最后一个入口为准',s.querySelectorAll('.panel').length===1&&panel.getAttribute('aria-label')==='程序员'&&!s.querySelector('.is-switching'));
    const active=s.querySelector('.bookmark[title="程序员"]'),indicator=s.querySelector('.bookmark-selection');
    check('选中背景跟随入口',Math.abs(active.getBoundingClientRect().left-indicator.getBoundingClientRect().left)<1&&Math.abs(active.offsetWidth-indicator.offsetWidth)<1);
    hover('设计');await settle();
    s.querySelector('.row[title="子菜单一"]').dispatchEvent(new PointerEvent('pointerenter'));await settle();
    s.querySelector('.row[title="子菜单二"]').dispatchEvent(new PointerEvent('pointerenter'));
    panel=[...s.querySelectorAll('.panel')].at(-1);
    check('子菜单之间使用同样过渡',s.querySelectorAll('.panel').length===2&&!!boxMotion(panel));
    await settle();
    check('最终菜单保持在视口内',[...s.querySelectorAll('.panel')].every(p=>{const b=p.getBoundingClientRect();return b.left>=0&&b.top>=0&&b.right<=innerWidth&&b.bottom<=innerHeight;}));
    hover('网盘');
    const closing=[...s.querySelectorAll('.panel')],pending=closing.flatMap(p=>p.getAnimations({subtree:true}));
    fixture.messages.fire({type:'TOGGLE_BAR'});
    check('关闭时清理全部动画与选中背景',!s.querySelector('.panel')&&!indicator.hasAttribute('data-visible')&&pending.every(a=>a.playState==='idle'));
    fixture.messages.fire({type:'TOGGLE_BAR'});
    click('网盘');await settle();
    s.querySelector('[aria-label="搜索书签"]').click();
    panel=s.querySelector('.panel');motion=boxMotion(panel);
    check('切换搜索时平滑调整宽度',!!motion&&parseFloat(motion.effect.getKeyframes().at(-1).width)>parseFloat(motion.effect.getKeyframes()[0].width));
    await settle();
  }catch(error){result.failures.push(error.message);console.error(error);}
  document.title=result.failures.length?'动效验证失败':'动效验证通过';
  const proof=document.createElement('pre');proof.id='test-proof';proof.style.cssText='position:fixed;bottom:0;left:0;right:0;z-index:2147483647;background:white;color:#162b48;padding:16px;font:13px monospace';proof.textContent=JSON.stringify(result,null,2);document.body.append(proof);
  await fetch('/test-result',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(result)});
})();
